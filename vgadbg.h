// vgadbg.h - минимальный текстовый вывод в VGA-текст (0xB8000, 80x25).
//
// Зачем: serial (COM1) на реальном ноуте нет, а VBE LFB на этом железе
// работает плохо (трогать его на этапе теста нельзя). Текстовый VGA-буфер
// 0xB8000 доступен всегда и не зависит ни от VBE, ни от serial — это
// последний надёжный канал диагностики. Пишем напрямую, без прокрутки
// примитивной логикой.
//
// ВАЖНО: 0xB8000 — это legacy VGA text. Если VBE-режим уже установлен
// (графика), запись в 0xB8000 обычно НЕ видна (адаптер в graphics mode).
// Поэтому vgadbg полезен ДО перехода в графику, либо как «маяк» для
// отладки в текстовом режиме QEMU/BIOS.
#ifndef VGADBG_H
#define VGADBG_H

// Очистить экран (заполнить пробелами, атрибут по умолчанию).
void vga_clear(void);

// Вывести строку в текущую позицию курсора (с переносом и прокруткой).
void vga_print(const char* s);

// Вывести строку в конкретную позицию (x,y), атрибут по умолчанию.
void vga_print_at(int x, int y, const char* s);

// Вывести int (десятичное) / hex (0x........) в текущую позицию.
void vga_print_int(int v);
void vga_print_hex(unsigned int v);

// Установить позицию курсора ввода/вывода (col,row).
void vga_set_pos(int col, int row);

// Установить атрибут по умолчанию (цвет). По умолчанию 0x07 (серый на чёрном).
void vga_set_attr(unsigned char attr);

#endif // VGADBG_H
