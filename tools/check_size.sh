#!/bin/sh
# Проверка размера kernel.bin. stage2.asm грузит ровно 496 секторов
# (резерв образа -R 512, ядро с LBA16 = 496*512 = 253952 байт).
# Если ядро больше — оно молча обрежется, .data не догрузится, система
# зависнет. Лучше упасть на сборке.
SZ=$(stat -c%s "$1" 2>/dev/null || echo 0)
MAX=253952
if [ "$SZ" -gt "$MAX" ]; then
  echo "ОШИБКА: $1 = $SZ байт > лимита $MAX (496 секторов)."
  echo "  Увеличь резерв образа (-R) и kern_sectors в stage2.asm, затем MAX тут."
  rm -f "$1"
  exit 1
fi
echo "kernel.bin: $SZ байт (лимит $MAX)"
exit 0
